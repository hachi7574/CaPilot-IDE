// ── Canonical timeline (§6.2) ───────────────────────────────────

pub type ItemId = String;
pub type TurnId = String;

#[derive(Clone, Debug, PartialEq, Eq, Serialize, Deserialize)]
#[serde(rename_all = "snake_case")]
pub enum MessageRole {
    User,
    Assistant,
}

#[derive(Clone, Debug, Serialize, Deserialize)]
pub struct MessageItem {
    pub item_id: ItemId,
    pub role: MessageRole,
    pub text: String,
    pub created_at: i64,
    #[serde(skip_serializing_if = "Option::is_none")]
    pub metadata: Option<serde_json::Value>,
}

#[derive(Clone, Debug, Default, PartialEq, Eq, Serialize, Deserialize)]
#[serde(rename_all = "snake_case")]
pub enum ToolCallStatus {
    #[default]
    Pending,
    Running,
    Completed,
    Failed,
    Cancelled,
}

#[derive(Clone, Debug, Serialize, Deserialize)]
pub struct ToolCallItem {
    pub item_id: ItemId,
    pub tool_name: String,
    #[serde(skip_serializing_if = "Option::is_none")]
    pub tool_input: Option<serde_json::Value>,
    #[serde(skip_serializing_if = "Option::is_none")]
    pub tool_output: Option<serde_json::Value>,
    #[serde(default)]
    pub status: ToolCallStatus,
    pub created_at: i64,
    #[serde(skip_serializing_if = "Option::is_none")]
    pub metadata: Option<serde_json::Value>,
}

#[derive(Clone, Debug, Serialize, Deserialize)]
pub struct PlanItem {
    pub item_id: ItemId,
    pub title: String,
    pub content: String,
    pub created_at: i64,
}

#[derive(Clone, Debug, Serialize, Deserialize)]
pub struct ErrorItem {
    pub item_id: ItemId,
    pub message: String,
    pub created_at: i64,
}

#[derive(Clone, Debug, Serialize, Deserialize)]
#[serde(tag = "kind", content = "data", rename_all = "snake_case")]
pub enum TimelineItem {
    UserMessage(MessageItem),
    AssistantMessage(MessageItem),
    Reasoning(MessageItem),
    ToolCall(ToolCallItem),
    Plan(PlanItem),
    Error(ErrorItem),
}

impl TimelineItem {
    /// Stable id used to stream updates to this item.
    pub fn item_id(&self) -> &str {
        match self {
            TimelineItem::UserMessage(m)
            | TimelineItem::AssistantMessage(m)
            | TimelineItem::Reasoning(m) => &m.item_id,
            TimelineItem::ToolCall(t) => &t.item_id,
            TimelineItem::Plan(p) => &p.item_id,
            TimelineItem::Error(e) => &e.item_id,
        }
    }
}

/// Terminal status of a timeline item (mostly tool calls; messages are complete
/// once their text stops appending).
#[derive(Clone, Debug, PartialEq, Eq, Serialize, Deserialize)]
#[serde(rename_all = "snake_case")]
pub enum ItemStatus {
    Pending,
    Complete,
    Failed,
    Cancelled,
}

/// A mutation to the canonical timeline. Streaming updates reuse the same
/// `item_id`; the UI upserts by id and never dedups by text.
#[derive(Clone, Debug, Serialize, Deserialize)]
#[serde(tag = "op", rename_all = "snake_case")]
pub enum TimelineEvent {
    Started { item: TimelineItem },
    Appended { item_id: ItemId, text_delta: String },
    Replaced { item: TimelineItem },
    Finished { item_id: ItemId, status: ItemStatus },
}

