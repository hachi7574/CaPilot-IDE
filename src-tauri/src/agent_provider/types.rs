// ── Error model ─────────────────────────────────────────────────

#[derive(Debug, thiserror::Error)]
pub enum AgentError {
    #[error("provider not registered: {0}")]
    ProviderNotFound(String),
    #[error("provider not available: {0}")]
    ProviderNotAvailable(String),
    #[error("agent not found: {0}")]
    AgentNotFound(String),
    #[error("session already has a live runtime")]
    SessionAlreadyActive,
    #[error("session is closed")]
    SessionClosed,
    #[error("permission request not found: {0}")]
    PermissionRequestNotFound(String),
    #[error("permission request already resolved: {0}")]
    PermissionAlreadyResolved(String),
    #[error("adapter rejected an unsupported content type")]
    UnsupportedContent,
    #[error("provider error: {0}")]
    Provider(String),
    #[error("protocol error: {0}")]
    Protocol(String),
    #[error("io error: {0}")]
    Io(#[from] std::io::Error),
    #[error("invalid argument: {0}")]
    InvalidArgument(String),
}

impl AgentError {
    /// Stable machine code for the daemon protocol (no message parsing).
    pub fn code(&self) -> &'static str {
        match self {
            AgentError::ProviderNotFound(_) => "provider_not_found",
            AgentError::ProviderNotAvailable(_) => "provider_not_available",
            AgentError::AgentNotFound(_) => "agent_not_found",
            AgentError::SessionAlreadyActive => "session_already_active",
            AgentError::SessionClosed => "session_closed",
            AgentError::PermissionRequestNotFound(_) => "permission_not_found",
            AgentError::PermissionAlreadyResolved(_) => "permission_already_resolved",
            AgentError::UnsupportedContent => "unsupported_content",
            AgentError::Provider(_) => "provider_error",
            AgentError::Protocol(_) => "protocol_error",
            AgentError::Io(_) => "io_error",
            AgentError::InvalidArgument(_) => "invalid_argument",
        }
    }
}

/// Convenience helpers shared by manager + adapters.
pub(crate) fn now_ms() -> i64 {
    std::time::SystemTime::now()
        .duration_since(std::time::UNIX_EPOCH)
        .map(|d| d.as_millis() as i64)
        .unwrap_or(0)
}
