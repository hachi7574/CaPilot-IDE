/// Every structured event a provider session can emit. `ContextUsageUpdated` is
/// an optional capability; account quota is never reported here (§12.3).
#[derive(Clone, Debug, Serialize, Deserialize)]
#[serde(tag = "event", content = "data", rename_all = "snake_case")]
pub enum AgentEvent {
    SessionReady(SessionReady),
    TurnStarted(TurnStarted),
    Timeline(TimelineEvent),
    PermissionRequested(PermissionRequest),
    PermissionResolved(PermissionResolution),
    ConfigUpdated(Vec<ConfigOption>),
    ContextUsageUpdated(ContextUsage),
    TurnCompleted(TurnCompleted),
    TurnCancelled(TurnCancelled),
    TurnFailed(TurnFailed),
    SessionClosed,
}

// ── Unified lifecycle status (§6.3) ─────────────────────────────

#[derive(Clone, Debug, PartialEq, Eq, Serialize, Deserialize)]
#[serde(rename_all = "snake_case")]
pub enum AgentStatus {
    /// Session created, still negotiating with the provider.
    Initializing,
    /// No foreground turn in flight.
    Idle,
    /// A foreground turn or explicit provider work event is active.
    Running,
    /// Blocked on an unresolved permission request.
    WaitingPermission,
    /// Blocked on a structured question/elicitation.
    WaitingInput,
    /// Terminal failure.
    Error,
    /// No live runtime (but the record may be resumable).
    Closed,
}

impl AgentStatus {
    pub fn is_live(&self) -> bool {
        matches!(
            self,
            AgentStatus::Initializing
                | AgentStatus::Idle
                | AgentStatus::Running
                | AgentStatus::WaitingPermission
                | AgentStatus::WaitingInput
        )
    }
}

