//! Provider-neutral domain model (architecture §5, §6, §9.3, §10.1).
//!
//! This module is Tauri-independent: no UI, no daemon wire types. Both the
//! daemon (structured agent API) and the GUI (snapshots/events) consume these
//! types, so a provider cannot smuggle its native shape past the boundary.
//! Every field here is the *general* rendering contract; provider-private data
//! may ride only inside `metadata` (`Option<serde_json::Value>`).

use serde::{Deserialize, Serialize};
use std::path::PathBuf;

// ── Provider capabilities (§5.1) ─────────────────────────────────

/// Static capability flags a provider reports after `initialize`/catalog.
/// UI features must be gated on these flags, never on a hardcoded provider id.
#[derive(Clone, Debug, Serialize, Deserialize, PartialEq, Eq)]
#[serde(rename_all = "camelCase")]
pub struct ProviderCapabilities {
    pub session_resume: bool,
    pub session_list: bool,
    pub structured_tools: bool,
    pub reasoning_stream: bool,
    pub permissions: bool,
    pub config_options: bool,
    pub slash_commands: bool,
    pub mcp_servers: bool,
    pub images: bool,
    pub context_usage: bool,
}

impl Default for ProviderCapabilities {
    fn default() -> Self {
        Self {
            session_resume: false,
            session_list: false,
            structured_tools: true,
            reasoning_stream: false,
            permissions: false,
            config_options: false,
            slash_commands: false,
            mcp_servers: false,
            images: false,
            context_usage: false,
        }
    }
}

// ── Provider catalog (§5.2) ─────────────────────────────────────

#[derive(Clone, Debug, Serialize, Deserialize)]
pub struct ModelDefinition {
    pub id: String,
    pub label: String,
    #[serde(skip_serializing_if = "Option::is_none")]
    pub context_window: Option<u64>,
    #[serde(default, skip_serializing_if = "Vec::is_empty")]
    pub reasoning_efforts: Vec<String>,
    #[serde(default)]
    pub is_default: bool,
}

#[derive(Clone, Debug, Serialize, Deserialize)]
pub struct SelectOption {
    pub id: String,
    pub label: String,
}

/// A runtime-discovered configuration knob (model, mode, thinking, sandbox,
/// network, ...). The UI groups by `category`; nothing here is hardcoded per
/// provider.
#[derive(Clone, Debug, Serialize, Deserialize)]
#[serde(tag = "type", rename_all = "snake_case")]
pub enum ConfigOption {
    Select {
        id: String,
        label: String,
        #[serde(skip_serializing_if = "Option::is_none")]
        category: Option<String>,
        current: String,
        options: Vec<SelectOption>,
    },
    Boolean {
        id: String,
        label: String,
        #[serde(skip_serializing_if = "Option::is_none")]
        category: Option<String>,
        current: bool,
    },
}

impl ConfigOption {
    pub fn id(&self) -> &str {
        match self {
            ConfigOption::Select { id, .. } => id,
            ConfigOption::Boolean { id, .. } => id,
        }
    }
}

/// Value for setting a [`ConfigOption`].
#[derive(Clone, Debug, PartialEq, Serialize, Deserialize)]
#[serde(untagged)]
pub enum ConfigValue {
    String(String),
    Bool(bool),
}

#[derive(Clone, Debug, Serialize, Deserialize)]
pub struct ProviderCatalog {
    pub models: Vec<ModelDefinition>,
    #[serde(default)]
    pub config_options: Vec<ConfigOption>,
    pub capabilities: ProviderCapabilities,
}

/// Result of `diagnostic()`: is the binary present, authenticated, and what
/// version does it report?
#[derive(Clone, Debug, Serialize, Deserialize)]
pub struct ProviderDiagnostic {
    pub available: bool,
    pub authenticated: bool,
    #[serde(skip_serializing_if = "Option::is_none")]
    pub version: Option<String>,
    #[serde(skip_serializing_if = "Option::is_none")]
    pub message: Option<String>,
}

/// One registered provider as exposed by `provider_list` (architecture §13).
/// `backend_kind` is `"acp"` | `"direct"` — the daemon is the authority on a
/// provider's backend type, so the frontend never hardcodes it when creating a
/// new agent (handoff §6 / §18.2).
#[derive(Clone, Debug, Serialize, Deserialize)]
pub struct ProviderInfo {
    pub provider_id: String,
    pub backend_kind: String,
}

