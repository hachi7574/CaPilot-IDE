/** Deep-map so every leaf is `string` — lets `en` share the shape of `zh`
 *  without requiring identical Chinese literal values. */
export type DeepStringify<T> = {
  [K in keyof T]: T[K] extends string
    ? string
    : T[K] extends Record<string, unknown>
      ? DeepStringify<T[K]>
      : T[K];
};

export type ZhMessages = DeepStringify<typeof zh>;
